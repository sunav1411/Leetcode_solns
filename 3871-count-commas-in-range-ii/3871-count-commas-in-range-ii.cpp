class Solution {
public:
    long long countCommas(long long n) {
        if(n < 1000) return 0;
        if(n <= 999999){
            return n-1000+1;
        }
        else if(n > 999999 & n <= 999999999){
            return (n-999999)*2 + (999999-1000+1);
        }
        else if(n > 999999999 & n <= 999999999999){
            return (n-999999999)*3 + (999999999-999999)*2 + (999999-1000+1);
        }
        else if(n > 999999999999 & n <= 999999999999999){
            return (n-999999999999)*4 + (999999999999-999999999)*3 + (999999999-999999)*2 + (999999-1000+1); 
        }
        else{
            return (n-999999999999999)*5 + (999999999999999-999999999999)*4 + (999999999999-999999999)*3 + (999999999-999999)*2 + (999999-1000+1);
        }
    }
};
